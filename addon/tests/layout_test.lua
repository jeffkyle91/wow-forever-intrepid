test("anchors that depend on each other in a circle are an error", function()
  local game = UI.new()
  local a, b = frame(game, nil, 10, 10), frame(game, nil, 10, 10)
  a:SetPoint("TOP", b)
  b:SetPoint("TOP", a)
  local layout = Layout.new(game)
  local ok, err = pcall(layout.rect, a)
  eq(ok, false)
  is_true(string.find(err, "anchor loop", 1, true) ~= nil)
end)

