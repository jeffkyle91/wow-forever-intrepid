#!/usr/bin/env python3
"""Writes IntrepidProbe/Items.lua from the Raid Desk's loot tables: the item ids that /ip bundle asks the game about.

  python3 tools/make-probe-items.py [loot-folder]

The default loot folder is data/loot of this repository. Only item ids are used (no
names: the game supplies those, which is the point of the check). Standard library only.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DEFAULT_LOOT = ROOT.parent / "data" / "loot"  # ROOT is addon/
OUT = ROOT / "IntrepidProbe" / "Items.lua"


def main():
    loot = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_LOOT
    files = sorted(loot.glob("*.json"))
    if not files:
        raise SystemExit(f"no loot tables in {loot}")
    ids, sources = set(), 0
    for path in files:
        table = json.loads(path.read_text(encoding="utf-8"))
        for source in table.get("sources", []):
            ids.update(source.get("itemIds", []))
            sources += 1
        ids.update(table.get("zoneWideItemIds", []))
    ordered = sorted(i for i in ids if isinstance(i, int) and 0 < i <= 100_000_000)
    lines = []
    for start in range(0, len(ordered), 10):
        lines.append("  " + ", ".join(str(i) for i in ordered[start:start + 10]) + ",")
    text = (
        "-- Generated by tools/make-probe-items.py from the Raid Desk's data/loot/*.json. Do not edit by hand.\n"
        f"-- {len(ordered)} item ids from {len(files)} loot tables ({sources} creatures). /ip bundle asks the game about each one.\n"
        "local _, ns = ...\n"
        "\n"
        "ns.ITEM_IDS = {\n"
        + "\n".join(lines) + "\n"
        "}\n"
    )
    OUT.write_text(text, encoding="utf-8", newline="")
    print(f"{len(ordered)} item ids written to {OUT}")


if __name__ == "__main__":
    main()
