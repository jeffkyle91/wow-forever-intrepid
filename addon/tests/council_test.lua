-- The council session engine (IntrepidManager/core/Council.lua): the loot master's queue and answers, and a raider's offers.
-- Invented names only.

local function load()
  local ns = {}
  load_core(ns, "Names", "Council")
  return ns.Council
end

-- A clock the test moves.
local function clock(start)
  local c = { t = start or 100 }
  c.now = function() return c.t end
  return c
end

local ITEM = "item:12345::::::::70"

test("the answers a raider can give, in the order of their claim, and the words that stand for them", function()
  local Council = load()
  local codes = {}
  for _, response in ipairs(Council.RESPONSES) do codes[#codes + 1] = response.code .. "=" .. response.label end
  deep_eq(codes, { "b=Best in slot", "u=Upgrade", "o=Off-spec", "p=Pass" })
  eq(Council.codeOf("bis"), "b")
  eq(Council.codeOf("BEST"), "b")
  eq(Council.codeOf("up"), "u")
  eq(Council.codeOf("Upgrade"), "u")
  eq(Council.codeOf("os"), "o")
  eq(Council.codeOf("off-spec"), "o")
  eq(Council.codeOf("offspec"), "o")
  eq(Council.codeOf("pass"), "p")
  eq(Council.codeOf("p"), "p")
  eq(Council.codeOf("greed"), nil)
  eq(Council.codeOf(nil), nil)
  eq(Council.label("u"), "Upgrade")
  eq(Council.label("z"), "z")
  eq(Council.response("p").short, "Pass")
end)

test("an item string is item: and digits, colons and minus signs, and nothing else", function()
  local Council = load()
  is_true(Council.isItem("item:12345"))
  is_true(Council.isItem("item:12345::::::::70:::::"))
  is_true(Council.isItem("item:12345:0:0:0:0:0:-5:0:70"))
  eq(Council.isItem("item:"), false)
  eq(Council.isItem("item:abc"), false)
  eq(Council.isItem("12345"), false)
  eq(Council.isItem("item:123|h"), false)
  eq(Council.isItem("item:123 456"), false)
  eq(Council.isItem(nil), false)
  eq(Council.isItem(12), false)
  eq(Council.isItem("item:1" .. string.rep(":1", 80)), false) -- longer than 120 bytes
  eq(Council.itemId("item:12345::::70"), 12345)
  eq(Council.itemId("nonsense"), nil)
end)

test("the queue takes items before the start, numbers them, and renumbers after a removal", function()
  local Council = load()
  local c = clock()
  local session = Council.newSession({ now = c.now, id = "k3f9" })
  eq(session.state, "building")
  eq(session.add(ITEM), 1)
  eq(session.add("item:777"), 2)
  eq(session.add("item:888"), 3)
  eq(session.count(), 3)
  local n, why = session.add("not an item")
  eq(n, nil)
  eq(why, "That is not an item.")
  deep_eq(session.items(), { { n = 1, item = ITEM }, { n = 2, item = "item:777" }, { n = 3, item = "item:888" } })
  eq(session.remove(2), true)
  deep_eq(session.items(), { { n = 1, item = ITEM }, { n = 2, item = "item:888" } })
  local ok, problem = session.remove(7)
  eq(ok, false)
  eq(problem, "There is no item 7.")
  -- the same item twice is two entries (two copies dropped)
  eq(session.add(ITEM), 3)
end)

test("at most twenty items, and none can be added or removed once the session runs", function()
  local Council = load()
  local c = clock()
  local session = Council.newSession({ now = c.now, id = "a" })
  for i = 1, 20 do eq(session.add("item:" .. i), i) end
  local n, why = session.add("item:99")
  eq(n, nil)
  eq(why, "At most 20 items in one session.")
  eq(session.start(), true)
  n, why = session.add("item:98")
  eq(n, nil)
  eq(why, "The session has started. Add items before you start it.")
  local ok, problem = session.remove(1)
  eq(ok, false)
  eq(problem, "The session has started.")
end)

test("a session starts with items only, takes its own timer within limits, and counts it down", function()
  local Council = load()
  local c = clock(1000)
  local session = Council.newSession({ now = c.now, id = "a" })
  local ok, why = session.start()
  eq(ok, false)
  eq(why, "Add at least one item first.")
  eq(session.remaining(), nil)
  session.add(ITEM)
  ok, why = session.start(3)
  eq(ok, false)
  eq(why, "The timer is 5 to 600 seconds.")
  ok, why = session.start(601)
  eq(ok, false)
  eq(why, "The timer is 5 to 600 seconds.")
  eq(session.state, "building")
  eq(session.start(90), true)
  eq(session.timer, 90)
  eq(session.state, "running")
  eq(session.startedAt(), 1000)
  eq(session.remaining(), 90)
  c.t = 1030.5
  eq(session.remaining(), 59.5)
  c.t = 1200
  eq(session.remaining(), 0)
  ok, why = session.start()
  eq(ok, false)
  eq(why, "The session has started already.")
  -- the default timer is a minute
  local plain = Council.newSession({ now = c.now, id = "b" })
  plain.add(ITEM)
  plain.start()
  eq(plain.timer, 60)
end)

test("an answer is taken while the session runs, can be changed, and the last one counts", function()
  local Council = load()
  local c = clock(500)
  local session = Council.newSession({ now = c.now, id = "a" })
  session.add(ITEM)
  session.add("item:777")
  local ok, why = session.respond(1, "Mirelle Dunmore", "u", "")
  eq(ok, false)
  eq(why, "There is no session taking answers.")
  session.start()
  c.t = 510
  local first, replaced = session.respond(1, "Mirelle Dunmore", "u", "my first one")
  eq(first, true)
  eq(replaced, false)
  c.t = 520
  first, replaced = session.respond(1, "mirelle  DUNMORE", "b", "changed my mind")
  eq(first, true)
  eq(replaced, true) -- the same player, however the name is spelled
  local rows = session.rows(1)
  eq(#rows, 1)
  eq(rows[1].who, "mirelle  DUNMORE")
  eq(rows[1].code, "b")
  eq(rows[1].label, "Best in slot")
  eq(rows[1].note, "changed my mind")
  eq(rows[1].at, 20)
  deep_eq(session.counts(1), { b = 1, u = 0, o = 0, p = 0, total = 1 })
  deep_eq(session.counts(2), { b = 0, u = 0, o = 0, p = 0, total = 0 })
end)

test("answers to bad items, codes and names are refused", function()
  local Council = load()
  local c = clock()
  local session = Council.newSession({ now = c.now, id = "a" })
  session.add(ITEM)
  session.start()
  local function refused(n, who, code)
    local ok, why = session.respond(n, who, code, "")
    eq(ok, false)
    return why
  end
  eq(refused(2, "Mirelle Dunmore", "u"), "There is no item 2.")
  eq(refused(1, "Mirelle Dunmore", "z"), "Unknown answer.")
  eq(refused(1, "", "u"), "No name.")
  eq(refused(1, nil, "u"), "No name.")
  eq(#session.rows(1), 0)
  eq(#session.rows(9), 0)
end)

test("the rows put the best claim first and the earlier answer first within a claim", function()
  local Council = load()
  local c = clock(0)
  local session = Council.newSession({ now = c.now, id = "a" })
  session.add(ITEM)
  session.start()
  local function answer(at, who, code) c.t = at session.respond(1, who, code, "") end
  answer(1, "Tavian Holt", "p")
  answer(2, "Mirelle Dunmore", "o")
  answer(3, "Jorren Ashvale", "u")
  answer(4, "Selwyn Crake", "b")
  answer(5, "Orla Finch", "u")
  answer(6, "Pell Marrow", "b")
  local order = {}
  for _, row in ipairs(session.rows(1)) do order[#order + 1] = row.who end
  deep_eq(order, { "Selwyn Crake", "Pell Marrow", "Jorren Ashvale", "Orla Finch", "Mirelle Dunmore", "Tavian Holt" })
  deep_eq(session.counts(1), { b = 2, u = 2, o = 1, p = 1, total = 6 })
end)

