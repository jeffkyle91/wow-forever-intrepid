  frame:SetAlpha(0.5)
  local function label(flags, shadow)
    local made = frame:CreateFontString(nil, "OVERLAY", "GameFontNormal")
    made:SetPoint("TOPLEFT")
    made:SetFont("Fonts\\FRIZQT__.TTF", 12, flags)
    if shadow then made:SetShadowColor(0, 0, 0, 1) end
    made:SetText(flags or "plain")
  end
  label("OUTLINE")
  label("THICKOUTLINE")
  label(nil, true)
  local html = shot(game).html
  expect(html, '<div class="x ol" ')
  expect(html, '<div class="x ol2" ')
  expect(html, '<div class="x sh" ')
  expect(html, "color:rgba(255,209,0,1);opacity:0.5")
end)

test("textures of one layer are drawn in the order they were made", function()
  local game, frame = setup()
  local first = frame:CreateTexture()
  first:SetAllPoints()
  first:SetColorTexture(1, 0, 0)
  local second = frame:CreateTexture()
  second:SetAllPoints()
  second:SetColorTexture(0, 1, 0)
  before(shot(game).html, "rgba(255,0,0,1)", "rgba(0,255,0,1)")
end)

test("a status bar's fill follows its range", function()
  local game = UI.new()
  local bar = game.env.CreateFrame("StatusBar")
  bar:SetSize(40, 10)
  bar:SetPoint("TOPLEFT", 0, 0)
  bar:SetMinMaxValues(50, 150)
  bar:SetValue(100)
  expect(shot(game).html, '<div class="bar-fill" style="left:0px;top:0px;width:20px;height:10px"></div>')
  bar:SetValue(500)
  expect(shot(game).html, 'width:40px;height:10px"></div>')
  bar:SetValue(0)
  expect(shot(game).html, 'width:0px;height:10px"></div>')
end)

test("a backdrop border without a size is one pixel wide", function()
  local game = UI.new()
  local frame = game.env.CreateFrame("Frame", nil, nil, "BackdropTemplate")
  frame:SetSize(100, 50)
  frame:SetPoint("TOPLEFT", 10, -20)
  frame:SetBackdrop({ edgeFile = "Interface\\Buttons\\WHITE8X8" })
  frame:SetBackdropBorderColor(1, 1, 1, 1)
  expect(shot(game).html, "border:1px solid rgba(255,255,255,1)")
end)

test("a multi-line edit box draws its wrapped text from the top", function()
  local game = UI.new()
  local edit = game.env.CreateFrame("EditBox")
  edit:SetMultiLine(true)
  edit:SetSize(100, 100)
  edit:SetPoint("TOPLEFT", 0, 0)
  edit:SetTextInsets(10, 10, 4, 4)
  edit:SetText(string.rep("a", 30)) -- 13 letters a line at 80 pixels: three lines
  local html = shot(game).html
  expect(html, "left:10px;top:4px;height:14px")
  expect(html, "left:10px;top:18px;height:14px")
  expect(html, "left:10px;top:32px;height:14px")
  expect(html, ">aaaaaaaaaaaaa</div>")
  expect(html, ">aaaa</div>")
  eq(has(html, "top:46px"), false)
end)

