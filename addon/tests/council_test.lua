-- A running session of two items, "Crown" and an item 777.
local function awarding()
  local Council = load()
  local clockObject = clock(0)
  local session = Council.newSession({ now = clockObject.now, id = "a" })
  session.add(ITEM, { name = "Crown", quality = 4 })
  session.add("item:777")
  session.start()
  return session, clockObject
end

test("the loot master awards an item to a raider, and can change it or take it back until the item is given", function()
  local session = awarding()
  eq(session.items()[1].winner, nil)
  eq(session.award(1, "Mirelle Dunmore"), true)
  eq(session.items()[1].winner, "Mirelle Dunmore")
  eq(session.items()[1].given, nil)
  eq(session.items()[2].winner, nil)
  eq(session.award(1, "Tavian Holt"), true) -- another winner replaces the first
  eq(session.items()[1].winner, "Tavian Holt")
  eq(session.award(1, nil), true) -- taken back
  eq(session.items()[1].winner, nil)
  eq(session.items()[1].name, "Crown")
  local ok, why = session.award(9, "Jorren Ashvale")
  eq(ok, false)
  eq(why, "There is no item 9.")
  ok, why = session.award(1, "")
  eq(ok, false)
  eq(why, "No name.")
  ok, why = session.award(1, 42)
  eq(ok, false)
  eq(why, "No name.")
end)

test("nothing is awarded before the start, and an item that was given is final", function()
  local Council = load()
  local clockObject = clock(0)
  local session = Council.newSession({ now = clockObject.now, id = "a" })
  session.add(ITEM)
  local ok, why = session.award(1, "Mirelle Dunmore")
  eq(ok, false)
  eq(why, "Start the session first.")
  session.start()
  eq(session.award(1, "Mirelle Dunmore"), true)
  ok, why = session.give(2)
  eq(ok, false)
  eq(why, "There is no item 2.")
  eq(session.give(1), true)
  eq(session.items()[1].given, true)
  ok, why = session.award(1, "Tavian Holt")
  eq(ok, false)
  eq(why, "Item 1 was given already.")
  ok = session.award(1, nil)
  eq(ok, false)
  eq(session.items()[1].winner, "Mirelle Dunmore")
  -- awards can still be made when the session is over
  local other = Council.newSession({ now = clockObject.now, id = "b" })
  other.add(ITEM)
  other.start()
  other.close()
  eq(other.award(1, "Orla Finch"), true)
end)

test("an item that nobody won cannot be given", function()
  local session = awarding()
  local ok, why = session.give(1)
  eq(ok, false)
  eq(why, "Item 1 is not awarded to anybody.")
  eq(session.items()[1].given, nil)
end)

test("what a raider has won and not been given is listed in order, names matching without regard to case, and the open awards are counted", function()
  local Council = load()
  local clockObject = clock(0)
  local session = Council.newSession({ now = clockObject.now, id = "a" })
  for i = 1, 4 do session.add("item:" .. (100 + i), { name = "Thing " .. i, quality = 4 }) end
  session.start()
  eq(session.pending(), 0)
  session.award(1, "Mirelle Dunmore")
  session.award(2, "Tavian Holt")
  session.award(4, "Mirelle Dunmore")
  eq(session.pending(), 3)
  local won = session.wonBy("mirelle  DUNMORE")
  eq(#won, 2)
  deep_eq({ won[1].n, won[1].item, won[1].name, won[1].quality, won[2].n }, { 1, "item:101", "Thing 1", 4, 4 })
  eq(#session.wonBy("Tavian Holt"), 1)
  eq(#session.wonBy("Orla Finch"), 0)
  eq(#session.wonBy(nil), 0)
  session.give(1)
  eq(session.pending(), 2)
  eq(#session.wonBy("Mirelle Dunmore"), 1) -- the given one is not listed again
  eq(session.wonBy("Mirelle Dunmore")[1].n, 4)
  session.award(2, nil)
  eq(session.pending(), 1)
end)
