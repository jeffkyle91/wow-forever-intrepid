-- Text estimates for the picture code (tests/support/metrics.lua). Invented names only.

local Metrics = dofile("tests/support/metrics.lua")

-- The tests of the line breaking and the drawing assert exact numbers, so they use the flat model of the text widths and
-- not the measured fonts, whose numbers change when the data is measured again (the window tests use the real ones).
local EstimateMetrics = dofile("tests/support/metrics.lua")
EstimateMetrics.estimate = true

local function near(actual, expected, message)
  if math.abs(actual - expected) > 0.001 then error((message or "") .. " expected " .. expected .. ", got " .. actual, 2) end
end

test("width grows with the size and with the letters, and wide letters take more room than narrow ones", function()
  near(Metrics.width("", 12), 0)
  near(Metrics.width("aaaa", 24), 2 * Metrics.width("aaaa", 12))
  is_true(Metrics.width("iiii", 12) < Metrics.width("aaaa", 12))
  is_true(Metrics.width("aaaa", 12) < Metrics.width("MMMM", 12))
  is_true(Metrics.width("aaaa", 12) < Metrics.width("AAAA", 12))
  is_true(Metrics.width("1111", 12) > Metrics.width("iiii", 12))
  near(Metrics.width("aaaa", 12), 24)
  near(Metrics.width("a a", 12), 12 + 12 * 0.28)
  near(Metrics.width("11", 10), 11)
end)

test("a multi-byte letter counts as one letter", function()
  local width = Metrics.width("\195\169", 10)
  is_true(width > 4 and width < 7)
  near(Metrics.width("a\195\169", 10), Metrics.width("a", 10) + width)
end)

test("escapes do not take room: colors, links, new lines, pipes", function()
  near(Metrics.width("|cffff0000aaaa|r", 12), Metrics.width("aaaa", 12))
  near(Metrics.width("|cff0070dd|Hitem:19019:0|h[Blade of the Fixture]|h|r", 12), Metrics.width("[Blade of the Fixture]", 12))
  near(Metrics.width("aaaa|nbb", 12), Metrics.width("aaaa", 12))
  near(Metrics.width("aaaa\nbb", 12), Metrics.width("aaaa", 12))
  near(Metrics.width("a||b", 12), Metrics.width("a|b", 12))
  near(Metrics.width("a|xb", 12), Metrics.width("a|xb", 12))
  near(Metrics.width("|cff12", 12), Metrics.width("|cff12", 12))
end)

test("an icon takes its width, or the width of the text when it has none", function()
  near(Metrics.width("|TInterface\\Icons\\INV_Misc_QuestionMark:16|t", 12), 16)
  near(Metrics.width("|TInterface\\Icons\\INV_Misc_QuestionMark:16:20|t", 12), 20)
  near(Metrics.width("|TInterface\\Icons\\INV_Misc_QuestionMark|t", 12), 12)
  near(Metrics.width("|Aitem-slot:14|a", 12), 14)
  near(Metrics.width("|Tbroken", 12), Metrics.width("|Tbroken", 12))
end)

test("parse reads colors, resets, links and new lines into runs", function()
  local runs = Metrics.parse("a|cff112233b|rc|nd")
  eq(#runs, 5)
  eq(runs[1].text, "a")
  eq(runs[1].color, nil)
  eq(runs[2].text, "b")
  near(runs[2].color[1], 0x11 / 255)
  near(runs[2].color[2], 0x22 / 255)
  near(runs[2].color[3], 0x33 / 255)
  near(runs[2].color[4], 1)
  eq(runs[3].text, "c")
  eq(runs[3].color, nil)
  is_true(runs[4].newline)
  eq(runs[5].text, "d")
  local link = Metrics.parse("|cffa335ee|Hitem:1:2|h[Blade]|h|r")
  eq(#link, 1)
  eq(link[1].text, "[Blade]")
  near(link[1].color[1], 0xa3 / 255)
  near(Metrics.parse("|c80ff0000x|r")[1].color[4], 0x80 / 255)
end)

test("layout wraps at spaces and trims the spaces at the ends of lines", function()
  local lines = Metrics.layout("aaaa aaaa aaaa", 12, 60, true)
  eq(#lines, 2)
  near(lines[1].width, 12 * 4 * 0.5 * 2 + 12 * 0.28)
  near(lines[2].width, 24)
  eq(#lines[1].runs, 1)
  eq(lines[1].runs[1].text, "aaaa aaaa")
  eq(lines[2].runs[1].text, "aaaa")
  eq(#Metrics.layout("aaaa aaaa", 12, 60, true), 1)
  eq(#Metrics.layout("aaaa aaaa", 12, 30, true), 2)
  eq(#Metrics.layout("aaaa aaaa aaaa", 12, 60, false), 1)
  eq(#Metrics.layout("aaaa aaaa aaaa", 12, nil, true), 1)
end)

test("layout keeps a word that is too long on its own line, and breaks at new lines", function()
  local lines = Metrics.layout("aaaaaaaaaaaa bb", 12, 30, true)
  eq(#lines, 2)
  is_true(lines[1].width > 30)
  eq(#Metrics.layout("one|ntwo|n|nfour", 12, nil, true), 4)
  eq(#Metrics.layout("", 12, 100, true), 1)
  eq(Metrics.layout("", 12, 100, true)[1].width, 0)
end)

test("layout keeps colors on the runs and counts icons in the line", function()
  local lines = Metrics.layout("|cff00ff00aaaa|r bb |TIcon:10|t", 12, nil, true)
  eq(#lines, 1)
  near(lines[1].runs[1].color[2], 1)
  eq(lines[1].runs[3].color, nil)
  near(lines[1].width, 24 + 12 * 0.28 + 12 + 12 * 0.28 + 10) -- the space before the icon stays; only a line's last spaces go
  eq(lines[1].runs[2].text, " bb ")
  is_true(lines[1].runs[3].icon ~= nil)
end)

test("spaces at the end of a wrapped line are dropped, spaces the text starts a line with stay", function()
  local lines = Metrics.layout("  aaaa", 12, nil, true)
  near(lines[1].width, 12 * 0.28 * 2 + 24)
  local wrapped = Metrics.layout("aaaa   aaaa", 12, 30, true)
  eq(#wrapped, 2)
  eq(#wrapped[1].runs, 1)
  eq(wrapped[1].runs[1].text, "aaaa")
  near(wrapped[1].width, 24)
  eq(wrapped[2].runs[1].text, "aaaa")
  local indented = Metrics.layout("a|n  b", 12, nil, true)
  near(indented[2].width, 12 * 0.28 * 2 + 6)
end)

test("line height follows the size, and the font objects of the client are known", function()
  eq(Metrics.line_height(12), 14)
  eq(Metrics.line_height(10), 12)
  eq(Metrics.line_height(16), 19)
  eq(Metrics.FONT_OBJECTS.GameFontNormal.size, 12)
  eq(Metrics.FONT_OBJECTS.GameFontNormalSmall.size, 10)
  eq(Metrics.FONT_OBJECTS.GameFontNormalLarge.size, 16)
  eq(Metrics.FONT_OBJECTS.GameFontHighlight.color[3], 1)
  eq(Metrics.FONT_OBJECTS.GameFontNormal.color[3], 0)
end)

test("every font object of the known-good list has a size and a color here", function()
  local UI = dofile("tests/support/strict_ui.lua")
  local known = UI.load_known()
  for name in pairs(known.present.fonts) do
    is_true(Metrics.FONT_OBJECTS[name] ~= nil)
  end
end)

test("pieces of one color are one run, pieces of different colors are not", function()
  local lines = Metrics.layout("one two |cffff0000red blue|r three", 12, nil, true)
  eq(#lines[1].runs, 3)
  eq(lines[1].runs[1].text, "one two ")
  eq(lines[1].runs[2].text, "red blue")
  eq(lines[1].runs[3].text, " three")
  eq(#Metrics.layout("|cffff0000a|r|cffff0000b|r", 12, nil, true)[1].runs, 2)
end)

test("a joined run keeps the width of its pieces", function()
  local run = Metrics.layout("one two", 12, nil, true)[1].runs[1]
  near(run.width, Metrics.width("one two", 12))
end)

test("breakLong starts a word wider than a line on a line of its own and cuts it at the character that overflows", function()
  -- an "a" is 6 pixels wide at size 12, so a line of 30 pixels takes five
  local lines = Metrics.layout(string.rep("a", 12), 12, 30, true, true)
  eq(#lines, 3)
  eq(lines[1].runs[1].text, "aaaaa")
  eq(lines[2].runs[1].text, "aaaaa")
  eq(lines[3].runs[1].text, "aa")
  near(lines[1].width, 30)
  near(lines[3].width, 12)
  -- without breakLong the word stays whole on one line
  eq(#Metrics.layout(string.rep("a", 12), 12, 30, true), 1)
  eq(#Metrics.layout(string.rep("a", 12), 12, 30, true, false), 1)
  -- the words before it stay on their line, and what comes after it follows on the line where it ended
  local mixed = Metrics.layout("aa " .. string.rep("b", 7) .. " cc", 12, 30, true, true)
  eq(#mixed, 3)
  eq(mixed[1].runs[1].text, "aa")
  eq(mixed[2].runs[1].text, "bbbbb")
  eq(mixed[3].runs[1].text, "bb cc")
  -- a word that fits a line by itself is not cut, and with no width to wrap at, or no wrapping, nothing is
  eq(#Metrics.layout("aaaa aaaa", 12, 30, true, true), 2)
  eq(#Metrics.layout(string.rep("a", 12), 12, nil, true, true), 1)
  eq(#Metrics.layout(string.rep("a", 12), 12, 30, false, true), 1)
  -- a character wider than the whole line still goes somewhere: one to a line
  eq(#Metrics.layout("WWW", 12, 5, true, true), 3)
end)

test("breakLong keeps the colors of the pieces and copes with a long string", function()
  local lines = Metrics.layout("|cff00ff00" .. string.rep("a", 12) .. "|r", 12, 30, true, true)
  eq(#lines, 3)
  near(lines[2].runs[1].color[2], 1)
  local big = Metrics.layout(string.rep("x", 20000), 10, 400, true, true)
  is_true(#big > 200)
  near(big[1].width, 400, nil)
end)

EstimateMetrics.estimate = false
