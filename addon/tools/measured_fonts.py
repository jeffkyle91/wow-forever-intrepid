#!/usr/bin/env python3
"""Turn what /im facts measured in the game into tests/support/measured_fonts.lua, the font data of the picture code.

Usage:
  python3 tools/measured_fonts.py path/to/IntrepidManager.lua            print the Lua file to stdout
  python3 tools/measured_fonts.py path/to/IntrepidManager.lua --write    write tests/support/measured_fonts.lua

The saved variables of the addon hold IntrepidManagerDB.facts.fonts: for each font object its file, size, flags, color,
the height of a line and, since build 0.0.5, every printable character's advance (its width in a line of that
character). Older results only have the width of each character alone, which the game rounds up: those are scaled down
by the factor the first run in the beta showed (0.846) and the font is marked approximate. Only fonts are read: nothing
of the file that names a player is used or written. The output is ASCII.
"""
import argparse
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "tests", "support", "measured_fonts.lua")
ALONE_TO_ADVANCE = 0.846  # a lone character is wider than the same character in a line; measured on 2026-10-21 (build 70450)


def load_parser():
    spec = importlib.util.spec_from_file_location("api_lint", os.path.join(HERE, "api_lint.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.parse_saved_variables


def as_list(table):
    """A Lua array that came back as a dict with the keys 1..n."""
    if isinstance(table, list):
        return table
    return [table[key] for key in sorted(table)]


def number(value):
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(facts, source_label):
    fonts = facts["fonts"]
    lines = [
        "-- Generated by tools/measured_fonts.py from /im facts (%s). Do not edit by hand." % source_label,
        "-- What the game says about its font objects: the file, size and color, the height of a line, and the advance of every",
        "-- printable character (95 numbers, from the space to the tilde, at the font's own size). Fonts marked approximate come",
        "-- from a run that only measured characters alone, which the game rounds up; the advances are those scaled down.",
        "return {",
    ]
    approximate = []
    for name in sorted(fonts):
        entry = fonts[name]
        if "size" not in entry or ("advances" not in entry and "chars" not in entry):
            continue
        exact = "advances" in entry
        advances = [float(v) for v in as_list(entry["advances"] if exact else entry["chars"])]
        if not exact:
            advances = [v * ALONE_TO_ADVANCE for v in advances]
            approximate.append(name)
        color = [float(v) for v in as_list(entry["color"])] if "color" in entry else [1, 1, 1, 1]
        lines.append("  %s = {" % name)
        lines.append("    size = %s, path = %s, flags = %s," % (number(entry["size"]), lua_string(entry.get("path", "")), lua_string(entry.get("flags", ""))))
        lines.append("    color = { %s }, lineHeight = %s," % (", ".join(number(v) for v in color), number(entry.get("lineHeight", entry["size"]))))
        if not exact:
            lines.append("    approximate = true,")
        lines.append("    advances = {")
        for start in range(0, len(advances), 12):
            lines.append("      " + ", ".join(number(v) for v in advances[start:start + 12]) + ",")
        lines.append("    },")
        lines.append("  },")
    lines.append("}")
    if approximate:
        sys.stderr.write("approximate (no advances in this run): %s\n" % ", ".join(approximate))
    return "\n".join(lines) + "\n"


def selftest():
    """Check the rendering on a small synthetic result. Returns 0 when all is well."""
    failures = []

    def check(name, condition):
        if not condition:
            failures.append(name)

    exact = {i + 1: 3.5 + i / 100 for i in range(95)}
    facts = {"fonts": {
        "GameFontExact": {"size": 12, "path": "Fonts\\FRIZQT__.TTF", "flags": "", "color": {1: 1, 2: 0.82, 3: 0, 4: 1},
                          "lineHeight": 11.81, "advances": exact, "chars": {i + 1: 9.0 for i in range(95)}},
        "GameFontAlone": {"size": 10, "path": "Fonts\\ARIALN.TTF", "flags": "OUTLINE", "lineHeight": 10.12,
                          "chars": {i + 1: 5.0 for i in range(95)}},
        "GameFontMissing": {"missing": True},
        "GameFontNoSize": {"error": "no"},
    }}
    text = render(facts, "build 1, addon 2")
    check("the output is ASCII", text.isascii())
    check("a measured font is in the output", "  GameFontExact = {" in text and "  GameFontAlone = {" in text)
    check("a font the game lacks, or that failed, is left out", "GameFontMissing" not in text and "GameFontNoSize" not in text)
    check("the source is named", "(build 1, addon 2)" in text)
    check("an exact font is not marked approximate", text.split("GameFontAlone")[0].count("approximate") == 1)  # only the header line
    check("a font measured alone is marked approximate and scaled", "approximate = true," in text and "4.23," in text)
    check("exact advances are kept as they are", "3.5, 3.51, 3.52" in text)
    check("the path keeps its backslash escaped", 'path = "Fonts\\\\FRIZQT__.TTF"' in text)
    check("the flags are kept", 'flags = "OUTLINE"' in text)
    check("95 advances to a font", text.count(",") > 0 and sum(len(line.split(",")) - 1 for line in text.split("advances = {")[1].split("},")[0].splitlines()) == 95)
    for failure in failures:
        print("FAIL  " + failure)
    print("measured_fonts selftest: %d checks, %d failed" % (10, len(failures)))
    return 1 if failures else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("saved", nargs="?", help="IntrepidManager.lua saved variables with IntrepidManagerDB.facts")
    parser.add_argument("--write", action="store_true", help="write tests/support/measured_fonts.lua instead of printing")
    parser.add_argument("--selftest", action="store_true", help="test this tool and exit")
    args = parser.parse_args()
    if args.selftest:
        sys.exit(selftest())
    if not args.saved:
        parser.error("the saved variables file is needed")
    with open(args.saved, encoding="utf8", errors="replace") as handle:
        saved = load_parser()(handle.read())
    db = saved.get("IntrepidManagerDB")
    if not isinstance(db, dict) or not isinstance(db.get("facts"), dict) or "fonts" not in db["facts"]:
        sys.exit("no IntrepidManagerDB.facts.fonts in that file (run /im facts in the game, then /reload)")
    facts = db["facts"]
    client = facts.get("client", {}).get("client")
    build = as_list(client)[1] if client else "unknown build"
    source = "build %s, addon %s" % (build, facts.get("version", "?"))
    text = render(facts, source)
    if not text.isascii():
        sys.exit("the output is not ASCII")
    if args.write:
        with open(OUT, "w", encoding="ascii", newline="\n") as handle:
            handle.write(text)
        print("wrote " + os.path.relpath(OUT, ROOT))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
