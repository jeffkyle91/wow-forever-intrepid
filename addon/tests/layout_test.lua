test("a widget with no anchor is not placed, and neither is what hangs from it", function()
  local game = UI.new()
  local lost = frame(game, nil, 100, 100)
  local child = frame(game, lost, 10, 10)
  child:SetPoint("CENTER")
  local label = lost:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  label:SetPoint("CENTER")
  local layout = Layout.new(game)
  eq(layout.rect(lost), nil)
  eq(layout.rect(child), nil)
  eq(layout.rect(label), nil)
  eq(layout.visible(child), false)
  eq(#layout.warnings, 1)
  eq(layout.warnings[1], "Frame #2 has no anchor, so the game would not show it")
  eq(layout.describe(label), "FontString of Frame #2")
  local named = game.env.CreateFrame("Frame", "IntrepidDemo")
  eq(layout.describe(named), "Frame 'IntrepidDemo'")
  eq(Layout.new(game).describe(game.env.UIParent), "Frame 'UIParent'")
end)

