test("text is cut to a limit of bytes with three dots, never inside a character, and short text is left alone", function()
  local _, _, Kit = setup()
  eq(Kit.cutText("short", 10), "short")
  eq(Kit.cutText("exactly ten", 11), "exactly ten")
  eq(Kit.cutText("a longer text than the limit", 12), "a longer ...")
  eq(Kit.cutText(nil, 5), "")
  eq(Kit.cutText("abcdefgh", 3), "...")
  eq(Kit.cutText("abcdefgh", 0), "...")
  -- an accented e is two bytes: a cut between them goes one byte further back
  eq(Kit.cutText(string.rep("a", 7) .. "\195\169\195\169\195\169", 11), string.rep("a", 7) .. "...")
  eq(Kit.cutText(string.rep("a", 8) .. "\195\169\195\169", 12), string.rep("a", 8) .. "\195\169\195\169") -- (12 bytes fit a limit of 12)
  eq(Kit.cutText(string.rep("a", 8) .. "\195\169\195\169", 11), string.rep("a", 8) .. "...") -- (cut between two characters)
  eq(Kit.cutText("\240\144\128\128\240\144\128\128\240\144\128\128", 9), "\240\144\128\128...") -- (one four byte character and the dots)
end)

test("a label's text is fitted to its box: about 6.5 pixels a character in the compact density, 7.5 in the roomy one", function()
