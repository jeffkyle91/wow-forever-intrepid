    local regions = game.state(list.frame).regions
    return regions[1], regions[2]
  end
  list.setContentHeight(80)
  local track, thumb = bar()
  eq(game.state(track).shown, false)
  eq(game.state(thumb).shown, false)
  list.setContentHeight(400)
