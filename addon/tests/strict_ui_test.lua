test("the keyboard focus belongs to one edit box at a time, and the boxes are told", function()
  local game = fullGame()
  local a, b = game.env.CreateFrame("EditBox"), game.env.CreateFrame("EditBox")
  local log = {}
  for name, box in pairs({ a = a, b = b }) do
    box:SetScript("OnEditFocusGained", function() log[#log + 1] = name .. " gained" end)
    box:SetScript("OnEditFocusLost", function() log[#log + 1] = name .. " lost" end)
  end
  eq(a:HasFocus(), false)
  a:SetFocus()
  eq(a:HasFocus(), true)
  a:SetFocus() -- again: nothing happens
  b:SetFocus()
  eq(a:HasFocus(), false)
  b:ClearFocus()
  a:ClearFocus() -- not the one with the focus: nothing happens
  deep_eq(log, { "a gained", "a lost", "b gained", "b lost" })
  eq(b:HasFocus(), false)
end)

test("game.paste needs a shown edit box with the focus, honors SetMaxLetters, and runs OnTextChanged as typed", function()
  local game = fullGame()
  local parent = game.env.CreateFrame("Frame")
  local box = game.env.CreateFrame("EditBox", nil, parent)
