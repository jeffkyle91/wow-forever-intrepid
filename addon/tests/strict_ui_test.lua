local function raises(fn, text)
  local ok, err = pcall(fn)
  if ok then error("expected an error containing '" .. text .. "'", 2) end
  if not string.find(tostring(err), text, 1, true) then
    error("expected an error containing '" .. text .. "', got: " .. tostring(err), 2)
  end
end

-- A game whose list has been changed first (to add an unverified or a missing name). The check of which kind of widget has
-- which method is off here: these tests use made-up names and call methods on whatever widget is at hand.
local function gameWith(edit)
  local known = UI.load_known()
  edit(known)
  return UI.new({ known = known, widgets = false })
end

-- A game whose list also knows every method the stand-in can do, for testing those behaviors: the real list lacks a
-- few getters that nothing needed yet (the test "a method without a place on the list is refused" shows that).
local function fullGame()
  local names = {}
  for name in pairs(UI.new().behaviors) do names[#names + 1] = name end
  return gameWith(function(known)
    for _, name in ipairs(names) do
      if known.present.methods[name] == nil and known.unverified.methods[name] == nil then known.present.methods[name] = "fl" end
    end
  end)
end

