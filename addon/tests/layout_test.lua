test("two anchors on opposite sides fix the size on that axis", function()
  local game = UI.new()
  local parent = frame(game, nil, 400, 300)
  parent:SetPoint("BOTTOMLEFT", 50, 50)
  local inner = frame(game, parent)
  inner:SetPoint("TOPLEFT", 10, -10)
  inner:SetPoint("BOTTOMRIGHT", -10, 10)
  local row = frame(game, parent)
  row:SetHeight(20)
  row:SetPoint("TOPLEFT", 0, 0)
  row:SetPoint("TOPRIGHT", -30, 0)
  local middle = frame(game, parent, 40, 40)
  middle:SetPoint("TOP", 0, -100)
  middle:SetPoint("BOTTOM", 0, 100)
  local layout = Layout.new(game)
  box(layout.rect(inner), 60, 60, 380, 280)
  box(layout.rect(row), 50, 330, 370, 20)
  box(layout.rect(middle), 230, 150, 40, 100) -- the two anchors fix the height; the size set is the width
end)

test("SetAllPoints fills the other region, by default the parent", function()
  local game = UI.new()
  local parent = frame(game, nil, 120, 80)
  parent:SetPoint("CENTER")
  local fill = parent:CreateTexture()
  fill:SetAllPoints()
  local other = frame(game, nil, 10, 10)
  other:SetPoint("BOTTOMLEFT", 5, 5)
  local follow = frame(game, parent)
  follow:SetAllPoints(other)
  local layout = Layout.new(game)
  box(layout.rect(fill), 900, 500, 120, 80)
  box(layout.rect(follow), 5, 5, 10, 10)
end)

test("scale multiplies size and offsets, and children inherit it", function()
  local game = UI.new()
  local parent = frame(game, nil, 100, 50)
  parent:SetScale(2)
  parent:SetPoint("BOTTOMLEFT", 10, 10)
  local child = frame(game, parent, 10, 10)
  child:SetPoint("TOPLEFT", 5, -5)
  local label = parent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  label:SetPoint("BOTTOMLEFT", 0, 3)
  label:SetText("aaaa")
  local layout = Layout.new(game)
  box(layout.rect(parent), 20, 20, 200, 100)
  box(layout.rect(child), 30, 90, 20, 20) -- its top left is 5 right and 5 down of the parent's, times the scale 2
  box(layout.rect(label), 20, 26, 48, 28) -- a region takes its parent's scale: the text is twice as large
end)

test("a font string without a size takes its text's size", function()
  local game = UI.new()
  local label = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  label:SetPoint("TOPLEFT", 10, -10)
  label:SetText("aaaa")
  local small = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormalSmall")
  small:SetPoint("TOPLEFT", 10, -40)
  small:SetText("aaaa|naaaaaa")
  local layout = Layout.new(game)
  box(layout.rect(label), 10, 1080 - 10 - 14, Metrics.width("aaaa", 12), 14)
  box(layout.rect(small), 10, 1080 - 40 - 24, Metrics.width("aaaaaa", 10), 24)
  eq(#layout.text(label).lines, 1)
  eq(layout.text(small).size, 10)
  eq(layout.text(small).lineHeight, 12)
end)

test("a font string wraps at the width its anchors or SetWidth give it, and takes the height of its lines", function()
  local game = UI.new()
  local parent = frame(game, nil, 60, 100)
  parent:SetPoint("TOPLEFT", 0, 0)
  local set = parent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  set:SetWidth(60)
  set:SetPoint("TOPLEFT")
  set:SetText("aaaa aaaa aaaa")
  local anchored = parent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  anchored:SetPoint("TOPLEFT", 0, -50)
  anchored:SetPoint("TOPRIGHT", -30, -50) -- 30 wide: every word on its own line
  anchored:SetText("aaaa aaaa aaaa")
  local layout = Layout.new(game)
  eq(#layout.text(set).lines, 2)
  box(layout.rect(set), 0, 1080 - 28, 60, 28)
  eq(#layout.text(anchored).lines, 3)
  near(layout.rect(anchored).width, 30)
  near(layout.rect(anchored).height, 42)
end)

test("max lines, no word wrap and an explicit height", function()
  local game = UI.new()
  local one = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  one:SetWidth(30)
  one:SetPoint("TOPLEFT", 0, 0)
  one:SetText("aaaa aaaa aaaa")
  one:SetMaxLines(1)
  local flat = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  flat:SetWidth(30)
  flat:SetPoint("TOPLEFT", 0, -20)
  flat:SetText("aaaa aaaa aaaa")
  flat:SetWordWrap(false)
  local tall = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  tall:SetSize(100, 50)
  tall:SetPoint("TOPLEFT", 0, -40)
  tall:SetText("aaaa")
  local layout = Layout.new(game)
  eq(#layout.text(one).lines, 1)
  near(layout.rect(one).height, 14)
  eq(#layout.text(flat).lines, 1)
  near(layout.rect(flat).width, 30)
  near(layout.rect(tall).height, 50)
end)

test("escapes do not take room in a font string", function()
  local game = UI.new()
  local plain = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  plain:SetPoint("TOPLEFT")
  plain:SetText("[Blade of the Fixture]")
  local colored = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
  colored:SetPoint("TOPLEFT")
  colored:SetText("|cffa335ee|Hitem:1:0|h[Blade of the Fixture]|h|r")
  local layout = Layout.new(game)
  near(layout.rect(colored).width, layout.rect(plain).width)
end)

test("SetFont wins over the font object; SetTextColor wins over its color", function()
  local game = UI.new()
  local label = game.env.UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge")
  label:SetPoint("TOPLEFT")
  label:SetText("aaaa")
  local layout = Layout.new(game)
  eq(layout.text(label).size, 16)
  deep_eq(layout.text(label).color, { 1, 0.82, 0, 1 })
  label:SetFont("Fonts\\ARIALN.TTF", 20, "OUTLINE")
  label:SetTextColor(0.5, 0.25, 0.1)
  layout = Layout.new(game)
  eq(layout.text(label).size, 20)
  eq(layout.text(label).flags, "OUTLINE")
  deep_eq(layout.text(label).color, { 0.5, 0.25, 0.1, 1 })
end)

