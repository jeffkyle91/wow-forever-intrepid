test("a raider's offers: a new one is kept with its deadline, a repeat changes nothing", function()
  local Council = load()
  local c = clock(1000)
  local offers = Council.newOffers({ now = c.now })
  local offer, isNew = offers.receive("k3f9", "Jorren Ashvale", 1, 2, 60, ITEM)
  eq(isNew, true)
  eq(offer.deadline, 1060)
  eq(offer.state, "open")
  eq(offer.count, 2)
  c.t = 1010
  local again, second = offers.receive("k3f9", "Jorren Ashvale", 1, 2, 60, ITEM)
  eq(second, false)
  eq(again, offer)
  eq(again.deadline, 1060) -- not moved
  offers.receive("k3f9", "Jorren Ashvale", 2, 2, 60, "item:777")
  eq(#offers.list(), 2)
  eq(offers.get("k3f9", 2).item, "item:777")
  eq(offers.get("zzzz", 1), nil)
  eq(offers.remaining(offer), 50)
  c.t = 5000
  eq(offers.remaining(offer), 0)
end)

test("a raider answers an offer, may change the answer, and is refused after the time is up", function()
  local Council = load()
  local c = clock(0)
  local offers = Council.newOffers({ now = c.now })
  offers.receive("k3f9", "Jorren Ashvale", 1, 1, 60, ITEM)
  local offer = offers.answer("k3f9", 1, "u", "my first")
  eq(offer.state, "answered")
  eq(offer.myCode, "u")
  eq(offer.myNote, "my first")
  offer = offers.answer("k3f9", 1, "b", "")
  eq(offer.myCode, "b")
  local none, why = offers.answer("k3f9", 5, "u", "")
  eq(none, nil)
  eq(why, "There is no such item on offer.")
  none, why = offers.answer("k3f9", 1, "zz", "")
  eq(none, nil)
  eq(why, "Unknown answer.")
  c.t = 61
  none, why = offers.answer("k3f9", 1, "p", "")
  eq(none, nil)
  eq(why, "Time is up for that item.")
  eq(offers.get("k3f9", 1).state, "closed")
  eq(offers.get("k3f9", 1).myCode, "b") -- what was sent before stays
end)

test("offers expire by their deadline and end with the session, and open lists those that still take an answer", function()
  local Council = load()
  local c = clock(0)
  local offers = Council.newOffers({ now = c.now })
  offers.receive("one", "Jorren Ashvale", 1, 1, 30, ITEM)
  offers.receive("two", "Jorren Ashvale", 1, 1, 90, "item:777")
  offers.receive("two", "Jorren Ashvale", 2, 2, 90, "item:888")
  eq(#offers.open(), 3)
  c.t = 31
  eq(#offers.open(), 2)
  local closed = offers.expire()
  eq(#closed, 1)
  eq(closed[1].sid, "one")
  eq(#offers.expire(), 0)
  closed = offers.endSession("two")
  eq(#closed, 2)
  eq(#offers.open(), 0)
  eq(#offers.endSession("two"), 0)
  eq(offers.remaining(offers.get("two", 1)), 0)
  eq(#offers.list(), 3)
end)

test("the limits are exact: item string length, timer bounds, the grace, the deadline", function()
  local Council = load()
  local c = clock(0)
  -- an item string of exactly 120 bytes passes, 121 does not
  local exact = "item:12345" .. string.rep(":1", 55)
  eq(#exact, 120)
  is_true(Council.isItem(exact))
  eq(Council.isItem(exact .. "1"), false)
  -- timer bounds: 5 and 600 are fine, a hair outside is not
  local function startWith(seconds)
    local session = Council.newSession({ now = c.now, id = "a" })
    session.add(ITEM)
    return session.start(seconds)
  end
  eq(startWith(5), true)
  eq(startWith(600), true)
  eq(startWith(4.99), false)
  eq(startWith(600.01), false)
  -- the grace: an answer exactly at the deadline plus the grace is taken, a hair later is not
  local session = Council.newSession({ now = c.now, id = "a" })
  session.add(ITEM)
  session.start(60)
  c.t = 63
  eq(session.respond(1, "Mirelle Dunmore", "u", ""), true)
  c.t = 63.01
  eq(session.respond(1, "Jorren Ashvale", "u", ""), false)
  c.t = 63
  eq(session.expire(), false) -- exactly at the end of the grace the session is still open
  c.t = 63.01
  eq(session.expire(), true)
end)

test("a raider's offer takes an answer up to its deadline, and not after", function()
  local Council = load()
  local c = clock(0)
  local offers = Council.newOffers({ now = c.now })
  offers.receive("a", "Jorren Ashvale", 1, 1, 60, ITEM)
  c.t = 60
  eq(#offers.open(), 1) -- exactly at the deadline it still counts as open
  eq(#offers.expire(), 0)
  eq(offers.answer("a", 1, "u", "").myCode, "u")
  c.t = 60.01
  eq(#offers.open(), 0)
  local none = offers.answer("a", 1, "p", "")
  eq(none, nil)
  eq(#offers.expire(), 0) -- the failed answer already closed it
  offers.receive("b", "Jorren Ashvale", 1, 1, 10, ITEM)
  c.t = 70.01
  eq(#offers.expire(), 1)
end)

