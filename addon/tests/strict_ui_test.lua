end)

test("scripts: SetScript, GetScript, fire with arguments, hooks run after the handler", function()
  local game = UI.new()
  local frame = game.env.CreateFrame("Button")
  local log = {}
  local function handler(self, button) log[#log + 1] = "click " .. button; return self end
  frame:SetScript("OnClick", handler)
  eq(frame:GetScript("OnClick"), handler)
  frame:HookScript("OnClick", function(_, button) log[#log + 1] = "hook " .. button end)
  frame:HookScript("OnClick", function(_, button) log[#log + 1] = "second hook " .. button end)
  eq(game.fire(frame, "OnClick", "LeftButton"), frame)
  deep_eq(log, { "click LeftButton", "hook LeftButton", "second hook LeftButton" })
  frame:SetScript("OnClick", nil)
  eq(frame:GetScript("OnClick"), nil)
  raises(function() frame:SetScript("OnClick", "not a function") end, "must be a function or nil")
  raises(function() frame:SetScript(nil, function() end) end, "Usage: SetScript")
  eq(game.fire(frame, "OnDoubleClick"), nil)
end)

test("events reach only the frames that registered for them", function()
  local game = fullGame()
  local a, b = game.env.CreateFrame("Frame"), game.env.CreateFrame("Frame")
  local got = {}
  a:SetScript("OnEvent", function(_, event, arg) got[#got + 1] = "a " .. event .. " " .. tostring(arg) end)
  b:SetScript("OnEvent", function(_, event) got[#got + 1] = "b " .. event end)
  a:RegisterEvent("LOOT_OPENED")
  b:RegisterEvent("LOOT_CLOSED")
  is_true(a:IsEventRegistered("LOOT_OPENED"))
  eq(a:IsEventRegistered("LOOT_CLOSED"), false)
  game.send("LOOT_OPENED", 1)
  game.send("LOOT_CLOSED")
  a:UnregisterEvent("LOOT_OPENED")
  game.send("LOOT_OPENED", 2)
  deep_eq(got, { "a LOOT_OPENED 1", "b LOOT_CLOSED" })
  b:UnregisterAllEvents()
  game.send("LOOT_CLOSED")
  eq(#got, 2)
end)

