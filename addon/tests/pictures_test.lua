test("a frame that clips holds what is inside it in a box of its own, in the box's coordinates", function()
  local game = UI.new()
  local scroll = game.env.CreateFrame("ScrollFrame", nil, nil, "UIPanelScrollFrameTemplate")
  scroll:SetSize(100, 50)
  scroll:SetPoint("TOPLEFT", 10, -10)
  local content = game.env.CreateFrame("Frame", nil, scroll)
  content:SetSize(100, 200)
  scroll:SetScrollChild(content)
  local fill = content:CreateTexture()
  fill:SetPoint("TOPLEFT", 5, -150)
  fill:SetSize(20, 20)
  fill:SetColorTexture(1, 0, 0)
  local clipper = game.env.CreateFrame("Frame")
  clipper:SetSize(30, 30)
  clipper:SetPoint("TOPLEFT", 200, -10)
  clipper:SetClipsChildren(true)
  local child = game.env.CreateFrame("Frame", nil, clipper)
  child:SetPoint("TOPLEFT", -5, 5)
  child:SetSize(50, 50)
  local inner = child:CreateTexture() -- what a clipping frame clips are its children; its own textures are not clipped
  inner:SetAllPoints()
  inner:SetColorTexture(0, 0, 1)
  scroll:SetVerticalScroll(100)
  local html = shot(game).html
  expect(html, '<div class="clip" style="left:10px;top:10px;width:100px;height:50px">')
  expect(html, 'style="left:5px;top:50px;width:20px;height:20px;background:rgba(255,0,0,1)"') -- 150 down, scrolled 100 up
  expect(html, '<div class="clip" style="left:200px;top:10px;width:30px;height:30px">')
  expect(html, 'style="left:-5px;top:-5px;width:50px;height:50px;background:rgba(0,0,255,1)"')
  before(html, '<div class="clip" style="left:10px', "rgba(255,0,0,1)")
  before(html, "rgba(255,0,0,1)", '<div class="clip" style="left:200px')
  local _, opened = string.gsub(html, '<div class="clip"', "")
  local _, closed = string.gsub(html, "</div>\n</div>", "")
  eq(opened, 2)
  is_true(closed >= 1)
end)

