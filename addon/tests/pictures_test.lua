local function has(html, text)
  return string.find(html, text, 1, true) ~= nil
end

local function expect(html, text)
  if not has(html, text) then error("expected the picture to contain: " .. text .. "\n" .. html, 2) end
end

local function before(html, first, second)
  local a, b = string.find(html, first, 1, true), string.find(html, second, 1, true)
  if not a or not b then error("missing " .. (a and second or first) .. "\n" .. html, 2) end
  is_true(a < b)
end

-- A game with one frame placed where the arithmetic is easy: 100 by 50, top left 10 right and 20 down of the screen.
local function setup()
  local game = UI.new()
  local frame = game.env.CreateFrame("Frame")
  frame:SetSize(100, 50)
  frame:SetPoint("TOPLEFT", 10, -20)
  return game, frame
end

local function shot(game, options)
  return Pictures.render(game, options or { crop = "screen" })
end

