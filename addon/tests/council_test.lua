test("answers still arrive during the grace after the timer, not after it, and the session closes then", function()
  local Council = load()
  local c = clock(0)
  local session = Council.newSession({ now = c.now, id = "a" })
  session.add(ITEM)
  session.start(60)
  c.t = 62.9
