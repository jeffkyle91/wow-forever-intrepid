    local made = frame:CreateTexture(nil, layer, nil, sublevel)
    made:SetAllPoints()
    made:SetColorTexture(color[1], color[2], color[3])
  end
  texture({ 1, 0, 0 }, "OVERLAY", 0)
  texture({ 0, 1, 0 }, "BACKGROUND", 0)
  texture({ 0, 0, 1 }, "ARTWORK", 1)
  texture({ 1, 1, 0 }, "ARTWORK", -1)
  local drawn = shot(layers).html
  before(drawn, "rgba(0,255,0,1)", "rgba(255,255,0,1)")
  before(drawn, "rgba(255,255,0,1)", "rgba(0,0,255,1)")
  before(drawn, "rgba(0,0,255,1)", "rgba(255,0,0,1)")
end)

