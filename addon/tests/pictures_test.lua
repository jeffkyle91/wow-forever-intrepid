test("frames come in the order of strata, level and creation, regions by layer and sublevel", function()
  local game = UI.new()
  local function box(color, strata, level)
    local frame = game.env.CreateFrame("Frame")
    frame:SetSize(10, 10)
    frame:SetPoint("CENTER")
    frame:SetFrameStrata(strata)
    frame:SetFrameLevel(level)
    local fill = frame:CreateTexture()
    fill:SetAllPoints()
    fill:SetColorTexture(color[1], color[2], color[3])
    return frame
  end
  box({ 0, 0, 1 }, "HIGH", 1) -- blue is made first but in a higher strata
  box({ 1, 0, 0 }, "LOW", 9)
  box({ 0, 1, 0 }, "LOW", 9) -- same strata and level: the later one on top
  box({ 1, 1, 0 }, "LOW", 2)
  local html = shot(game).html
  before(html, "rgba(255,255,0,1)", "rgba(255,0,0,1)")
  before(html, "rgba(255,0,0,1)", "rgba(0,255,0,1)")
  before(html, "rgba(0,255,0,1)", "rgba(0,0,255,1)")

  local layers = UI.new()
