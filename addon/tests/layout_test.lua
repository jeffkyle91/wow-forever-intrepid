test("visibility needs every parent shown and a place; alpha multiplies down the tree", function()
  local game = UI.new()
  local parent = frame(game, nil, 100, 100)
  parent:SetPoint("CENTER")
  parent:SetAlpha(0.5)
  local child = frame(game, parent, 10, 10)
  child:SetPoint("CENTER")
  child:SetAlpha(0.5)
  local region = child:CreateTexture()
  region:SetAllPoints()
  region:SetAlpha(0.5)
  local layout = Layout.new(game)
  is_true(layout.visible(region))
  near(layout.alpha(region), 0.125)
  near(layout.alpha(parent), 0.5)
  parent:Hide()
  layout = Layout.new(game)
  eq(layout.visible(child), false)
  eq(layout.visible(region), false)
end)

test("a multi-line edit box wraps its text at its width less the insets, and cuts a word that is too long", function()
  local game = UI.new()
  local edit = game.env.CreateFrame("EditBox")
  edit:SetMultiLine(true)
  edit:SetSize(100, 200)
  edit:SetPoint("TOPLEFT", 0, 0)
  edit:SetTextInsets(10, 10, 0, 0) -- 80 pixels for the text; an "a" is 6 pixels wide at the default size
  edit:SetText(string.rep("a", 40))
  local info = Layout.new(game).text(edit)
  eq(#info.lines, 4) -- 13, 13, 13 and 1
  near(info.lines[1].width, 78)
  near(info.lines[4].width, 6)
  -- without SetTextInsets the guess for a box applies (6 on each side: 88 pixels, 14 letters a line)
  local plain = game.env.CreateFrame("EditBox")
  plain:SetMultiLine(true)
  plain:SetSize(100, 200)
  plain:SetPoint("TOPLEFT", 0, -300)
  plain:SetText(string.rep("a", 40))
  eq(#Layout.new(game).text(plain).lines, 3)
  -- a box of one line does not wrap
  local single = game.env.CreateFrame("EditBox")
  single:SetSize(100, 20)
  single:SetPoint("TOPLEFT", 0, -600)
  single:SetText(string.rep("a", 40))
  eq(#Layout.new(game).text(single).lines, 1)
end)

