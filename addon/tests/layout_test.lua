-- Where widgets end up on the screen (tests/support/layout.lua). The stand-in screen is 1920 by 1080, y counted
-- upward as in the game. Invented names only.

local UI = dofile("tests/support/strict_ui.lua")
local Layout = dofile("tests/support/layout.lua")
local Metrics = dofile("tests/support/metrics.lua")

-- The tests of the line breaking and the drawing assert exact numbers, so they use the flat model of the text widths and
-- not the measured fonts, whose numbers change when the data is measured again (the window tests use the real ones).
local EstimateMetrics = dofile("tests/support/metrics.lua")
EstimateMetrics.estimate = true

local function near(actual, expected, message)
  if math.abs(actual - expected) > 0.001 then error((message or "") .. " expected " .. expected .. ", got " .. tostring(actual), 2) end
end

local function box(rect, left, bottom, width, height)
  near(rect.left, left, "left")
  near(rect.bottom, bottom, "bottom")
  near(rect.width, width, "width")
  near(rect.height, height, "height")
  near(rect.right, left + width, "right")
  near(rect.top, bottom + height, "top")
end

local function frame(game, parent, width, height)
  local made = game.env.CreateFrame("Frame", nil, parent)
  if width then made:SetSize(width, height) end
  return made
end

test("the screen is the root: 1920 by 1080 from the bottom left", function()
  local game = UI.new()
  box(Layout.new(game).rect(game.env.UIParent), 0, 0, 1920, 1080)
end)

test("one anchor and a size: the anchor's point sits at the offset, y counted upward", function()
  local game = UI.new()
  local a = frame(game, nil, 300, 200)
  a:SetPoint("TOPLEFT", 10, -20)
  local b = frame(game, nil, 100, 50)
  b:SetPoint("CENTER")
  local c = frame(game, nil, 100, 50)
  c:SetPoint("BOTTOMRIGHT", -5, 5)
  local d = frame(game, nil, 100, 50)
  d:SetPoint("TOP", 0, -10)
  local layout = Layout.new(game)
  box(layout.rect(a), 10, 860, 300, 200)
  box(layout.rect(b), 910, 515, 100, 50)
  box(layout.rect(c), 1815, 5, 100, 50)
  box(layout.rect(d), 910, 1020, 100, 50)
end)

