-- The widget kit (IntrepidManager/ui/Kit.lua) on the strict stand-in widgets. Invented names only.

local UI = dofile("tests/support/strict_ui.lua")
local StockTemplates = dofile("tests/support/stock_templates.lua")
local Layout = dofile("tests/support/layout.lua")

-- A game with the stock templates, the kit loaded and a kit made.
local function setup(options, known, stock)
  local game = UI.new({ known = known })
  if stock ~= false then StockTemplates.install(game) end
  local ns = {}
  game.load("IntrepidManager/ui/Kit.lua", ns)
  return game, ns.UI.Kit.new(options), ns.UI.Kit
end

local function near(actual, expected)
  if math.abs(actual - expected) > 0.001 then error("expected " .. expected .. ", got " .. tostring(actual), 2) end
end

test("both densities have every size and only font objects the probe found", function()
  local game, _, Kit = setup()
  for name, m in pairs(Kit.DENSITIES) do
    for _, key in ipairs({ "row", "itemRow", "icon", "headIcon", "pad", "gap", "button", "input", "inputFont", "check", "header",
        "windowWidth", "windowHeight", "leftWidth", "bar", "banner", "colPos", "colName", "colRole", "colHere", "popupWidth" }) do
      is_true(type(m[key]) == "number")
    end
    for _, key in ipairs({ "text", "gold", "title" }) do
      is_true(game.known.present.fonts[m[key]] ~= nil)
    end
    eq(m.name, name)
  end
  is_true(Kit.DENSITIES.compact.row < Kit.DENSITIES.roomy.row)
  is_true(Kit.DENSITIES.compact.itemRow < Kit.DENSITIES.roomy.itemRow)
  is_true(Kit.DENSITIES.compact.windowWidth < Kit.DENSITIES.roomy.windowWidth)
end)

